    private void jButtonLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonLoginActionPerformed
        // TODO add your handling code here:
        
               //read from the text fields
        String librarianId = jTextID.getText().trim();
        String librarianName = jTextName.getText().trim();
        String librarianEmail = jTextEmail.getText().trim();
        String librarianPhone = jTextPhone.getText().trim();
        
        //check if any of the fields are empty 
        if (librarianId.isEmpty() || librarianName.isEmpty() || librarianEmail.isEmpty() 
                                                || librarianPhone.isEmpty()) {
            jLabelInfo.setText("Enter all data!");
            return;
        } else {
            LibrarianGUI lib = new LibrarianGUI();
            lib.show();
            this.dispose();
        }
        
        
        LibrarianDAO librarianDAO = new LibrarianDAO();
        int insertStatus = -1;
        try {
            if (librarianDAO.findLibrarianById(librarianId) != null) {
                jLabelInfo.setText("librarian_id "+librarianId+ " already exists!");
                return;
            }
            
            insertStatus = librarianDAO.addNewLibrarian(librarianId, librarianName, librarianEmail, librarianPhone);
        } catch (SQLException sqlex) {
            jLabelInfo.setText(sqlex.getMessage());
        }
        
        if (insertStatus == 1) {
            jLabelInfo.setText("Record for "+librarianName+ " added!");
        }
        else {
            jLabelInfo.setText("Error adding record for "+librarianName);
        }

    }//GEN-LAST:event_jButtonLoginActionPerformed


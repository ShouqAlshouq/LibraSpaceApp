    private void jButtonLogin1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonLogin1ActionPerformed
        // TODO add your handling code here:
        String studID = jTextStudID1.getText().trim();
        String StudName = jTextStudName1.getText().trim();
        String StudEmail = jTextStudEmail1.getText().trim();
        String StudPhone = jTextStudPhone1.getText().trim();
        
        //check if any of the fields are empty 
        if (studID.isEmpty() || StudName.isEmpty() || StudEmail.isEmpty() 
                                                || StudPhone.isEmpty()) {
            jLabelInfo.setText("Enter all data!");
            return;
        } else {
            LibraryMenuGUI lib = new LibraryMenuGUI();
            lib.show();
            this.dispose();
        }
        
        StudentDAO studentDAO = new StudentDAO();
        int insertStatus = -1;
        try {
            if (studentDAO.findStudentById(studID) != null) {
                jLabelInfo.setText("StudID "+studID+ " already exists!");
                return;
            }
            
            //add the new employee 
            insertStatus = studentDAO.addNewStudent(studID, StudName, StudEmail, StudPhone, "none");
        } catch (SQLException sqlex) {
            jLabelInfo.setText(sqlex.getMessage());
        }
        
        if (insertStatus == 1) {
            jLabelInfo.setText("Record for "+StudName+ " added!");
        }
        else {
            jLabelInfo.setText("Error adding record for "+StudName);
        }

    }//GEN-LAST:event_jButtonLogin1ActionPerformed


    private void jButtonFindRoomActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonFindRoomActionPerformed
        String roomID = jTextFieldRoomID.getText().trim();
        if (roomID.isEmpty()) {
            jLabelStatus.setText("Enter Room ID to find.");
            return;
        }

        RoomDAO roomDAO = new RoomDAO();
        try {
            Room r = roomDAO.findRoomById(roomID);
            if (r == null) {
                jLabelStatus.setText(roomID + " not found.");
                return;
            }

            // populate fields
            jTextFieldRoomID.setText(r.getRoomId());
            jTextFieldRoomName.setText(r.getRoomName());
            jTextFieldRoomCapacity.setText(String.valueOf(r.getCapacity()));
            jComboBoxRoomStatus.setSelectedItem(r.getStatus());

            // Show single row in table
            Vector columnNames = new Vector();
            columnNames.add("room_id");
            columnNames.add("room_name");
            columnNames.add("capacity");
            columnNames.add("status");

            Vector row = new Vector();
            row.add(r.getRoomId());
            row.add(r.getRoomName());
            row.add(r.getCapacity());
            row.add(r.getStatus());

            Vector rows = new Vector();
            rows.add(row);

            jTable1 = new JTable(rows, columnNames);
            jScrollPane1.setViewportView(jTable1);

            jLabelStatus.setText("Room displayed.");
        } catch (SQLException ex) {
            jLabelStatus.setText("DB Error: " + ex.getMessage());
        }
    }//GEN-LAST:event_jButtonFindRoomActionPerformed

    private void jButtonAddRoomActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonAddRoomActionPerformed
        String roomID = jTextFieldRoomID.getText().trim();
        String roomName = jTextFieldRoomName.getText().trim();
        String capacityText = jTextFieldRoomCapacity.getText().trim();
        String status = (String) jComboBoxRoomStatus.getSelectedItem();

        if (roomID.isEmpty() || roomName.isEmpty() || capacityText.isEmpty()) {
            jLabelStatus.setText("Enter Room ID, Room Name and Capacity.");
            return;
        }

        int capacity;
        try {
            capacity = Integer.parseInt(capacityText);
        } catch (NumberFormatException nfex) {
            jLabelStatus.setText("Capacity must be a number!");
            return;
        }

        RoomDAO roomDAO = new RoomDAO();
        try {
            // check duplicate
            Room existing = roomDAO.findRoomById(roomID);
            if (existing != null) {
                jLabelStatus.setText("Room ID " + roomID + " already exists!");
                return;
            }

            int insertStatus = roomDAO.addNewRoom(roomID, roomName, capacity, status);
            if (insertStatus == 1) {
                jLabelStatus.setText("Room '" + roomID + "' added successfully.");
            } else {
                jLabelStatus.setText("Error adding room.");
            }
        } catch (SQLException ex) {
            jLabelStatus.setText("DB Error: " + ex.getMessage());
        }
    }//GEN-LAST:event_jButtonAddRoomActionPerformed

    private void jButtonUpdateRoomActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonUpdateRoomActionPerformed
        String roomID = jTextFieldRoomID.getText().trim();
        String roomName = jTextFieldRoomName.getText().trim();
        String capacityText = jTextFieldRoomCapacity.getText().trim();
        String status = (String) jComboBoxRoomStatus.getSelectedItem();

        if (roomID.isEmpty()) {
            jLabelStatus.setText("Enter Room ID to update!");
            return;
        }

        if (roomName.isEmpty() || capacityText.isEmpty()) {
            jLabelStatus.setText("Enter Room Name and Capacity to update!");
            return;
        }

        int capacity;
        try {
            capacity = Integer.parseInt(capacityText);
        } catch (NumberFormatException nfex) {
            jLabelStatus.setText("Capacity must be a number!");
            return;
        }

        RoomDAO roomDAO = new RoomDAO();
        try {
            int updateStatus = roomDAO.updateRoom(roomID, roomName, capacity, status);
            if (updateStatus == 1) {
                jLabelStatus.setText("Room '" + roomID + "' updated successfully.");
            } else {
                jLabelStatus.setText("Room ID '" + roomID + "' not found or not updated.");
            }
        } catch (SQLException ex) {
            jLabelStatus.setText("DB Error: " + ex.getMessage());
        }
    }//GEN-LAST:event_jButtonUpdateRoomActionPerformed

    private void jButtonDeleteRoomActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonDeleteRoomActionPerformed
        String roomID = jTextFieldRoomID.getText().trim();

        if (roomID.isEmpty()) {
            jLabelStatus.setText("Enter Room ID to delete!");
            return;
        }

        RoomDAO roomDAO = new RoomDAO();
        try {
            int del = roomDAO.deleteRoom(roomID);
            if (del == 1) {
                jLabelStatus.setText("Room '" + roomID + "' deleted successfully.");
            } else {
                jLabelStatus.setText("Room ID '" + roomID + "' not found.");
            }
        } catch (SQLException ex) {
            jLabelStatus.setText("DB Error: " + ex.getMessage());
        }
    }//GEN-LAST:event_jButtonDeleteRoomActionPerformed

    private void jButtonShowAllRoomsActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonShowAllRoomsActionPerformed
        RoomDAO roomDAO = new RoomDAO();
        List<Room> roomList = null;
        try {
            roomList = roomDAO.getAllRooms();
        } catch (SQLException ex) {
            jLabelStatus.setText("Database error: " + ex.getMessage());
            return;
        }

        Vector rowDataVector = new Vector();
        Vector columnDataVector = null;
        for (Room r : roomList) {
            columnDataVector = new Vector();
            columnDataVector.add(r.getRoomId());
            columnDataVector.add(r.getRoomName());
            columnDataVector.add(r.getCapacity());
            columnDataVector.add(r.getStatus());

            rowDataVector.add(columnDataVector);
        }

        Vector columnNamesVector = new Vector();
        columnNamesVector.add("room_id");
        columnNamesVector.add("room_name");
        columnNamesVector.add("capacity");
        columnNamesVector.add("status");

        jTable1 = new JTable(rowDataVector, columnNamesVector);
        jScrollPane1.setViewportView(jTable1);
        jLabelStatus.setText("Rooms loaded.");
    }//GEN-LAST:event_jButtonShowAllRoomsActionPerformed


    private void jButtonReservedRoomActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonReservedRoomActionPerformed
        // Find reservation by reservation id AND student id, then show it
        String resId = jTextReservationID.getText().trim();
        String studentId = jTextStudentID.getText().trim();

        if (resId.isEmpty() || studentId.isEmpty()) {
            jLabelStatus.setText("Enter Reservation ID and Student ID.");
            return;
        }

        ReservationDAO reservationDAO = new ReservationDAO();
        try {
            Reservation res = reservationDAO.findReservationById(resId);
            if (res == null) {
                jLabelStatus.setText("Reservation not found.");
                return;
            }

            if (!res.getStudent_id().equals(studentId)) {
                jLabelStatus.setText("Reservation does not belong to that student.");
                return;
            }

            Vector columnNames = new Vector();
            columnNames.add("reservation_id");
            columnNames.add("student_id");
            columnNames.add("room_id");
            columnNames.add("reservation_date");

            Vector row = new Vector();
            row.add(res.getReservation_Id());
            row.add(res.getStudent_id());
            row.add(res.getRoom_Id());
            row.add(res.getReservation_date());

            Vector rows = new Vector();
            rows.add(row);

            jTable = new JTable(rows, columnNames);
            jScrollPane1.setViewportView(jTable);

            jLabelStatus.setText("Reservation displayed.");
        } catch (SQLException ex) {
            jLabelStatus.setText("DB Error: " + ex.getMessage());
        }
   
    }//GEN-LAST:event_jButtonReservedRoomActionPerformed


    private void AddReservationActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_AddReservationActionPerformed
        // Create a new reservation
        String studId = jTextStudentID.getText().trim();
        String roomNum = jTextRoomNum.getText().trim();
        String date = jTextDate.getText().trim();

        // basic validation
        if (studId.isEmpty() || roomNum.isEmpty() || date.isEmpty()) {
            jLabelStatus.setText("Enter Student ID, Room ID and Date.");
            return;
        }

        // restrict allowed room IDs
        if (!(roomNum.equalsIgnoreCase("RM001") || roomNum.equalsIgnoreCase("RM002") || roomNum.equalsIgnoreCase("RM003") || roomNum.equalsIgnoreCase("RM004") || roomNum.equalsIgnoreCase("RM005"))) {
            jLabelStatus.setText("Invalid Room ID. Choose RM001, RM002, RM003, RM004, or RM005.");
            return;
        }

        StudentDAO studentDAO = new StudentDAO();
        RoomDAO roomDAO = new RoomDAO();
        ReservationDAO reservationDAO = new ReservationDAO();

        try {
            // verify student exists
            Student s = studentDAO.findStudentById(studId);
            if (s == null) {
                jLabelStatus.setText("Student ID not found.");
                return;
            }

            // verify room exists
            Room room = roomDAO.findRoomById(roomNum);
            if (room == null) {
                jLabelStatus.setText("Room does not exist.");
                return;
            }

            // prevent booking if room status indicates not available
            String roomStatus = room.getStatus();
            if (roomStatus != null && roomStatus.equalsIgnoreCase("Occupied")) {
                jLabelStatus.setText("Room not available (status: " + roomStatus + ").");
                return;
            }

            // generate reservation id using existing reservations count (simple approach)
            List<Reservation> all = reservationDAO.getAllReservations();
            int next = (all == null) ? 1 : all.size() + 1;
            String reservationID = String.format("R%03d", next);

            // insert reservation
            int inserted = reservationDAO.addNewReservation(reservationID, studId, roomNum, date, "Pending", "L001");
            if (inserted == 1) {
                // update room status to Pending (so librarians know)
                // use RoomDAO update method (same-style)
                roomDAO.updateRoom(room.getRoomId(), room.getRoomName(), room.getCapacity(), "Pending");

                jLabelStatus.setText("Reservation created and waiting for librarian approval. Your Reservation ID is: " + reservationID);
                jTextReservationID.setText(reservationID);
            } else {
                jLabelStatus.setText("Could not create reservation.");
            }

        } catch (SQLException ex) {
            jLabelStatus.setText("DB Error: " + ex.getMessage());
        }
  

    }//GEN-LAST:event_AddReservationActionPerformed


    private void jButtonAddBookActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonAddBookActionPerformed
        String bookID = jTextFieldBookID.getText().trim();
        String title = jTextFieldUpdateBook.getText().trim();
        String author = jTextFieldFindBook.getText().trim();
        String publisher = jTextFieldPublisher.getText().trim();
        String genre = jTextFieldGenre.getText().trim();
        String pagesText = jTextFieldNumPages.getText().trim();
        String isBorrowedText = jTextFieldIsBorrowed.getText().trim();

        if (bookID.isEmpty() || title.isEmpty() || author.isEmpty() || publisher.isEmpty() || genre.isEmpty() || pagesText.isEmpty() || isBorrowedText.isEmpty()) {
            jLabelStatus.setText("Enter all book details!");
            return;
        }

        int numPages;
        try {
            numPages = Integer.parseInt(pagesText);
        } catch (NumberFormatException nfex) {
            jLabelStatus.setText("Number of pages must be a number!");
            return;
        }

        boolean isBorrowed = parseBooleanField(isBorrowedText);

        BooksDAO booksDAO = new BooksDAO();
        try {
            // check duplicate by listing all books and ensuring ID not used (BooksDAO doesn't have findById)
            List<Book> all = booksDAO.getAllBooks();
            for (Book b : all) {
                if (b.getBookID().equals(bookID)) {
                    jLabelStatus.setText("BookID " + bookID + " already exists!");
                    return;
                }
            }

            int status = booksDAO.addNewBook(bookID, title, author, publisher, genre, numPages, isBorrowed);
            if (status == 1) {
                jLabelStatus.setText("Book '" + title + "' added successfully.");
            } else {
                jLabelStatus.setText("Error adding book.");
            }
        } catch (SQLException ex) {
            jLabelStatus.setText("DB Error: " + ex.getMessage());
        }

    }//GEN-LAST:event_jButtonAddBookActionPerformed

    private void jButtonUpdateBookActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonUpdateBookActionPerformed
        // read inputs
        String bookID = jTextFieldBookID.getText().trim();
        String title = jTextFieldUpdateBook.getText().trim();
        String author = jTextFieldFindBook.getText().trim();
        String publisher = jTextFieldPublisher.getText().trim();
        String genre = jTextFieldGenre.getText().trim();
        String pagesText = jTextFieldNumPages.getText().trim();
        String isBorrowedText = jTextFieldIsBorrowed.getText().trim();

        if (bookID.isEmpty()) {
            jLabelStatus.setText("Enter Book ID to update!");
            return;
        }

        if (title.isEmpty() || author.isEmpty() || publisher.isEmpty() || genre.isEmpty() || pagesText.isEmpty() || isBorrowedText.isEmpty()) {
            jLabelStatus.setText("Enter all fields to update!");
            return;
        }

        int numPages;
        try {
            numPages = Integer.parseInt(pagesText);
        } catch (NumberFormatException nfex) {
            jLabelStatus.setText("Number of pages must be a number!");
            return;
        }

        boolean isBorrowed = parseBooleanField(isBorrowedText);

        BooksDAO booksDAO = new BooksDAO();
        try {
            int updateStatus = booksDAO.updateBook(bookID, title, author, publisher, genre, numPages, isBorrowed);
            if (updateStatus == 1) {
                jLabelStatus.setText("Book '" + bookID + "' updated successfully.");
            } else {
                jLabelStatus.setText("Book ID '" + bookID + "' not found or not updated.");
            }
        } catch (SQLException ex) {
            jLabelStatus.setText("DB Error: " + ex.getMessage());
        }
    }//GEN-LAST:event_jButtonUpdateBookActionPerformed

    private void jButtonFindBookActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonFindBookActionPerformed
String title = jTextFieldUpdateBook.getText().trim();

        if (title.isEmpty()) {
            jLabelStatus.setText("Enter a book title to search!");
            return;
        }

        BooksDAO booksDAO = new BooksDAO();
        try {
            Book book = booksDAO.findBookByName(title);
            if (book == null) {
                jLabelStatus.setText(title + " not found!");
                return;
            }

            // populate fields with found book
            jTextFieldBookID.setText(book.getBookID());
            jTextFieldUpdateBook.setText(book.getTitle());
            jTextFieldFindBook.setText(book.getAuthor());
            jTextFieldPublisher.setText(book.getPublisher());
            jTextFieldGenre.setText(book.getGenre());
            jTextFieldNumPages.setText(String.valueOf(book.getNumPages()));
            jTextFieldIsBorrowed.setText(String.valueOf(book.isIsBorrowed()));

            jLabelStatus.setText("Book found and loaded.");
        } catch (SQLException ex) {
            jLabelStatus.setText("DB Error: " + ex.getMessage());
        }
    }//GEN-LAST:event_jButtonFindBookActionPerformed

    private void jButtonDeleteBookActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonDeleteBookActionPerformed
// try to get bookID from delete field; fall back to main book id field
        String bookIdFromDeleteField = jTextFieldBookID.getText().trim();
        String bookID = bookIdFromDeleteField.isEmpty() ? jTextFieldBookID.getText().trim() : bookIdFromDeleteField;

        if (bookID.isEmpty()) {
            jLabelStatus.setText("Enter Book ID to delete.");
            return;
        }

        BooksDAO booksDAO = new BooksDAO();
        try {
            int deleteStatus = booksDAO.deleteBook(bookID);
            if (deleteStatus == 1) {
                jLabelStatus.setText("Book '" + bookID + "' deleted successfully.");
            } else {
                jLabelStatus.setText("Book ID '" + bookID + "' not found.");
            }
        } catch (SQLException ex) {
            jLabelStatus.setText("DB Error: " + ex.getMessage());
        }
    }//GEN-LAST:event_jButtonDeleteBookActionPerformed

    private void jButtonShowAllBookActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonShowAllBookActionPerformed
        BooksDAO booksDAO = new BooksDAO();
        List<Book> bookList = null;
        try {
            bookList = booksDAO.getAllBooks();
        } catch (SQLException sqlex) {
            jLabelStatus.setText("Database error: " + sqlex.getMessage());
            return;
        }

        // convert the bookList into vector data for JTable
        Vector rowDataVector = new Vector();
        Vector columnDataVector = null;
        for (Book book : bookList) {
            columnDataVector = new Vector();
            columnDataVector.add(book.getBookID());
            columnDataVector.add(book.getTitle());
            columnDataVector.add(book.getAuthor());
            columnDataVector.add(book.getPublisher());
            columnDataVector.add(book.getGenre());
            columnDataVector.add(book.getNumPages());
            columnDataVector.add(book.isIsBorrowed());

            rowDataVector.add(columnDataVector);
        }

        Vector columnNamesVector = new Vector();
        columnNamesVector.add("bookID");
        columnNamesVector.add("title");
        columnNamesVector.add("author");
        columnNamesVector.add("publisher");
        columnNamesVector.add("genre");
        columnNamesVector.add("numPages");
        columnNamesVector.add("isBorrowed");

        jTable1 = new JTable(rowDataVector, columnNamesVector);
        jScrollPane1.setViewportView(jTable1);
        jLabelStatus.setText("Books loaded.");
        
    }//GEN-LAST:event_jButtonShowAllBookActionPerformed

